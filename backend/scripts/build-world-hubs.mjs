// Builds src/data/world-hubs.ts: the airports, seaports and cities used to pick hubs
// automatically anywhere in the world. Run again to refresh the data (it rarely changes).
//
//   node scripts/build-world-hubs.mjs <folder with the downloaded files>
//
// Download into that folder first (all public domain):
//   airports.csv                          https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
//   ne_10m_ports.geojson                  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_ports.geojson
//   ne_10m_populated_places_simple.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder with the downloaded files");
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "world-hubs.ts");

const round = (n) => Math.round(n * 1e4) / 1e4;
const NO_ISO = { SOL: "SO", CYN: "CY", KOS: "XK" };

// Cities: every populated place (used to tell which country a point is in), with population.
const places = JSON.parse(readFileSync(path.join(dir, "ne_10m_populated_places_simple.geojson"), "utf8")).features.map((f) => {
  const p = f.properties;
  const iso = /^[A-Z]{2}$/.test(p.iso_a2 ?? "") ? p.iso_a2 : NO_ISO[p.adm0_a3];
  return [p.nameascii || p.name, round(p.latitude), round(p.longitude), iso ?? "", p.pop_max ?? 0];
});

const km = (aLat, aLng, bLat, bLng) => {
  const rad = Math.PI / 180;
  const h =
    Math.sin(((bLat - aLat) * rad) / 2) ** 2 + Math.cos(aLat * rad) * Math.cos(bLat * rad) * Math.sin(((bLng - aLng) * rad) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};
const countryAt = (lat, lng) => {
  let best = "";
  let bestKm = Infinity;
  for (const [, pLat, pLng, iso] of places) {
    const d = km(lat, lng, pLat, pLng);
    if (iso && d < bestKm) [best, bestKm] = [iso, d];
  }
  return best;
};

// Airports with scheduled passenger/cargo flights. Tier 1 = large international, 2 = medium.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') (field += '"'), i++;
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") row.push(field), (field = "");
    else if (c === "\n") row.push(field), rows.push(row), (row = []), (field = "");
    else if (c !== "\r") field += c;
  }
  if (field || row.length) row.push(field), rows.push(row);
  return rows;
}
const [header, ...airportRows] = parseCsv(readFileSync(path.join(dir, "airports.csv"), "utf8"));
const col = (name) => header.indexOf(name);
const [cType, cName, cLat, cLng, cIso, cSched, cIata] = ["type", "name", "latitude_deg", "longitude_deg", "iso_country", "scheduled_service", "iata_code"].map(col);
const airports = airportRows
  .filter((r) => (r[cType] === "large_airport" || r[cType] === "medium_airport") && r[cSched] === "yes" && /^[A-Z]{3}$/.test(r[cIata] ?? ""))
  .map((r) => [r[cName], r[cIata], round(Number(r[cLat])), round(Number(r[cLng])), r[cIso], r[cType] === "large_airport" ? 1 : 2]);

// Seaports: the larger ones (Natural Earth scalerank 3-7; lower is bigger), with their country.
const ports = JSON.parse(readFileSync(path.join(dir, "ne_10m_ports.geojson"), "utf8"))
  .features.filter((f) => f.properties.scalerank <= 7)
  .map((f) => {
    const [lng, lat] = f.geometry.coordinates;
    return [f.properties.name, round(lat), round(lng), countryAt(lat, lng), f.properties.scalerank];
  });

const header_ = `// GENERATED by scripts/build-world-hubs.mjs. Do not edit by hand.
// Sources (public domain): OurAirports (ourairports.com) and Natural Earth (naturalearthdata.com).
/* eslint-disable */
`;
const body = `${header_}
/** [name, IATA code, lat, lng, ISO country, tier: 1 large international / 2 medium] */
export const AIRPORTS: [string, string, number, number, string, number][] = ${JSON.stringify(airports)};

/** [name, lat, lng, ISO country, size rank: 3 biggest .. 7] */
export const PORTS: [string, number, number, string, number][] = ${JSON.stringify(ports)};

/** [name, lat, lng, ISO country, population] */
export const CITIES: [string, number, number, string, number][] = ${JSON.stringify(places)};
`;
writeFileSync(out, body);
console.log(`airports ${airports.length}, ports ${ports.length}, cities ${places.length}, ${(body.length / 1024).toFixed(0)} KB -> ${out}`);
